/**
 * @file    pl_task.h
 * @brief   任务创建薄封装 —— 失败时留痕，不阻断
 *
 * 本工程的任务栈与堆都是定长算好的，创建失败意味着"账没算对"。而 osThreadNew
 * 失败时返回 NULL，多数调用点不检查 —— 那样少的是一个任务，日志里却什么都没有，
 * 现场表现为"某个功能莫名不工作"。
 */

#pragma once

#include "cmsis_os2.h"

/**
 * @brief 创建任务；失败时打印任务名与当时的堆余量，并累加失败计数
 *
 * **只记录，不重启也不停机**，理由：
 *   分配失败是**确定性**的 —— 堆是定长数组（heap_4），这次创建不下，下次上电
 *   同样创建不下。重启只会陷入循环（而且循环比降级更难查，日志也拿不出来），
 *   停机则让设备彻底不可用。相比之下，"设备继续运行、少一个功能、日志里有一条
 *   明确记录"是三者里最好排查的。
 *
 * 若调用方的后续逻辑依赖该任务，应自行判断返回值并降级（例如通道任务创建失败
 * 就不注册该通道），但不必因此改变控制流去"补救"。
 *
 * 真正的防线是堆够用 —— 所以日志里带上堆余量，上电后用 `app_diag` 的周期输出
 * 把账算清楚。
 *
 * @return 任务句柄；失败返回 NULL
 */
osThreadId_t pl_task_new(osThreadFunc_t fn, void *arg, const osThreadAttr_t *attr);

/** @brief 本次上电以来的任务创建失败次数（0 = 正常） */
uint16_t pl_task_fail_count(void);
